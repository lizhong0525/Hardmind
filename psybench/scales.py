# -*- coding: utf-8 -*-
"""
psybench.scales — 标准化心理量表库
====================================

本模块定义了「心镜」平台使用的通用心理学测评量表（均为公开、标准化的
经典量表，用于 AI 心理仿真对象的量化测评）：

  - UCLA-3  孤独量表（第三版，20 题，1-4 分，9 道反向题，总分 20-80）
  - PHQ-9   病人健康问卷抑郁量表（9 题，0-3 分，总分 0-27）
  - GAD-7   广泛性焦虑障碍量表（7 题，0-3 分，总分 0-21）
  - PSS-10  知觉压力量表（10 题，0-4 分，4 道反向题，总分 0-40）
  - WHO-5   五条目心理健康指数（5 题，0-5 分，原始分 0-25，换算 0-100）

每个量表包含：条目文本、选项、反向题索引、计分规则、人群常模与分级切点。
常模数据来源于公开文献（见 docs/01_初步调研.md 的参考文献），仅用于把
AI 仿真对象的量表分数映射到"相当于人群中的什么水平"，实现"心理状态可量化"。
"""

from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class Scale:
    """一张标准化心理量表。"""
    key: str                      # 唯一标识，如 "ucla3"
    name: str                     # 中文全称
    abbr: str                     # 英文缩写
    items: List[str]              # 条目文本（已中文化）
    options: List[str]            # 选项标签，从低到高
    min_score: int                # 单题最低分
    max_score: int                # 单题最高分
    reverse_items: List[int]      # 反向计分条目（1-based 索引）
    construct: str                # 测量的心理构念（用于报告，不进施测提示词）
    period: str                   # 评定时间窗，如"最近两周"
    score_range: tuple            # (最低总分, 最高总分)
    score_multiplier: int = 1     # 原始总分 → 报告总分的换算倍数（如 WHO-5 ×4）
    bands: List[tuple] = field(default_factory=list)   # [(上限, "分级名称"), ...]
    norm_note: str = ""           # 常模说明（参考文献）

    def n_items(self) -> int:
        return len(self.items)

    def score(self, raw_items: List[int]) -> int:
        """由原始作答计算总分（自动处理反向题与换算倍数）。

        注意：band() 与 score_range 均针对换算后的总分；
        WHO-5 的原始总分 0-25 会乘以 4 得到 0-100。
        """
        if len(raw_items) != self.n_items():
            raise ValueError(
                f"{self.key}: 需要 {self.n_items()} 个作答，收到 {len(raw_items)} 个")
        total = 0
        for i, v in enumerate(raw_items):
            v = int(v)
            if (i + 1) in self.reverse_items:
                v = (self.min_score + self.max_score) - v
            total += v
        return total * self.score_multiplier

    def band(self, total: int) -> str:
        """根据总分返回分级名称。"""
        for upper, label in self.bands:
            if total <= upper:
                return label
        return self.bands[-1][1] if self.bands else ""


