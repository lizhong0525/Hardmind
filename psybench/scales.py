# 注册所有量表，便于按 key 检索
ALL_SCALES = {s.key: s for s in [UCLA3, PHQ9, GAD7, PSS10, WHO5]}


def get_scale(key: str) -> Scale:
    if key not in ALL_SCALES:
        raise KeyError(f"未知量表: {key}，可用: {list(ALL_SCALES)}")
    return ALL_SCALES[key]
